const DOCKERFILE = `FROM node:22-slim
WORKDIR /app
COPY package.json ./
RUN npm install --omit=dev --no-audit --no-fund
COPY . .
ENV MCP_TRANSPORT=http PORT=8080
EXPOSE 8080
CMD ["node", "server.mjs"]
`;

export interface Meta { name: string; slug: string; baseUrl: string; secretEnv: string[]; tools: string[] }

export function slugify(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 49).replace(/-+$/, "") || "mcp-server";
}

export function runtimeConfig(cur: Curation) {
  return { name: cur.server.name, version: "1.0.0", baseUrl: cur.server.baseUrl, timeoutMs: cur.server.timeoutMs,
    auth: cur.auth, tools: cur.tools };
}

export function build(spec: Spec, cur: Curation, out: string, specName: string, curName: string): string[] {
  mkdirSync(out, { recursive: true });
  const written: string[] = [];
  const w = (f: string, text: string, keep = false) => {
    const p = join(out, f);
    if (keep && existsSync(p)) return;
    writeFileSync(p, text, "utf8");
    written.push(f);
  };
  const slug = slugify(cur.server.name);
  const secretEnv = Object.entries(cur.auth).filter(([k, v]) => k.endsWith("_env") && v).map(([, v]) => String(v));
  const toolNames = Object.values(cur.tools).map((t) => t.name);
  w("openapi.json", JSON.stringify(withOperationIds(spec), null, 2)); // fallback ids match mcp.yaml keys
  w("mcpsmith.config.json", JSON.stringify(runtimeConfig(cur), null, 2) + "\n");
  w("server.mjs", SERVER_MJS(specName, curName));
  copyFileSync(RUNTIME_PATH, join(out, "mcpsmith-runtime.mjs"));
  written.push("mcpsmith-runtime.mjs");
  w("custom-tools.mjs", CUSTOM_TOOLS, true);
  w("package.json", JSON.stringify({
    name: slug, version: "1.0.0", private: true, type: "module", main: "server.mjs",
    scripts: { start: "node server.mjs" }, engines: { node: ">=20" },
    dependencies: { "@modelcontextprotocol/server": SDK_VERSIONS.server, "@modelcontextprotocol/node": SDK_VERSIONS.node },
  }, null, 2) + "\n");
  w("Dockerfile", DOCKERFILE);
  w(".env.example", [`API_BASE_URL=${cur.server.baseUrl}`, ...secretEnv.map((v) => `${v}=`)].join("\n") + "\n");
  w(".dockerignore", "node_modules\n.env\n");
  w(".gcloudignore", "node_modules/\n.env\n.git/\n");
  w(".gitignore", "node_modules/\n.env\n");
  const meta: Meta = { name: cur.server.name, slug, baseUrl: cur.server.baseUrl, secretEnv, tools: toolNames };
  w("mcpsmith.json", JSON.stringify(meta, null, 2) + "\n");
  w("README.md", `# ${cur.server.name}

Generated by [mcpsmith](https://www.npmjs.com/package/mcpsmith) from \`${specName}\` + \`${curName}\`.

**Tools (${toolNames.length}):** ${toolNames.map((n) => `\`${n}\``).join(", ")}

## Run

\`\`\`bash
npm install
cp .env.example .env    # fill in, then export the values
npm start               # Streamable HTTP on :8000/mcp (PORT to change)
MCP_TRANSPORT=stdio node server.mjs   # for clients that launch a subprocess
\`\`\`

Cloud Run (private by default): \`npx mcpsmith deploy . --region europe-west1\`

Gemini CLI: \`npx mcpsmith connect .\` (local) — or \`--url http://localhost:3000/mcp\` behind \`gcloud run services proxy\`

## Change it

- Spec or curation changed → \`npx mcpsmith build ${specName} ${curName} -o .\` (overwrites everything except \`custom-tools.mjs\`)
- Composite / hand-written tools → \`custom-tools.mjs\`
- Check the tool surface → \`npx mcpsmith test . --spec ${specName}\`
`);
  return written;
}
