// Ship a generated server to Cloud Run, and wire it into Gemini CLI.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import type { Meta } from "./build.js";
import { UserError } from "./spec.js";

export function readMeta(folder: string): Meta {
  const p = join(folder, "mcpsmith.json");
  if (!existsSync(p)) throw new UserError(`${folder} wasn't generated by mcpsmith — run mcpsmith build first.`);
  return JSON.parse(readFileSync(p, "utf8"));
}

const secretName = (service: string, v: string) => `${service}-${v}`.toLowerCase().replace(/_/g, "-");
const shq = (s: string) => (/^[A-Za-z0-9_\-./:=,@]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`);

export function deployCommand(folder: string, service: string, region: string, project: string | undefined,
  pub: boolean, secrets: Record<string, string>): string[] {
  const meta = readMeta(folder);
  const cmd = ["gcloud", "run", "deploy", service, "--source", folder, "--region", region, "--quiet"];
  if (project) cmd.push("--project", project);
  cmd.push("--set-env-vars", `MCP_TRANSPORT=http,API_BASE_URL=${meta.baseUrl}`);
  if (meta.secretEnv.length) {
    cmd.push("--set-secrets", meta.secretEnv.map((v) => `${v}=${secrets[v] || secretName(service, v)}:latest`).join(","));
  }
  cmd.push(pub ? "--allow-unauthenticated" : "--no-allow-unauthenticated");
  return cmd;
}

export function deploy(o: { folder: string; service?: string; region: string; project?: string; pub: boolean;
  secret: string[]; dryRun: boolean }): number {
  const meta = readMeta(o.folder);
  const service = o.service || meta.slug;
  if (!/^[a-z]([-a-z0-9]{0,47}[a-z0-9])?$/.test(service)) {
    throw new UserError(`Cloud Run service names are lowercase letters, digits and dashes: '${service}'`);
  }
  const secrets = Object.fromEntries(o.secret.map((s) => { const i = s.indexOf("="); return [s.slice(0, i), s.slice(i + 1)]; }));
  const cmd = deployCommand(o.folder, service, o.region, o.project, o.pub, secrets);
  const p = o.project ? ` --project ${o.project}` : "";
  console.log(o.pub
    ? "Deploying to Cloud Run as PUBLIC: anyone with the URL can call your API through it, using your credentials. Only do this for public, read-only APIs."
    : "Deploying to Cloud Run (private: callers need roles/run.invoker)");
  if (meta.secretEnv.length) {
    console.log("\nCredentials come from Secret Manager. Create them once:");
    for (const v of meta.secretEnv) {
      console.log(`  printf %s "$${v}" | gcloud secrets create ${secrets[v] || secretName(service, v)} --data-file=-${p}`);
    }
    console.log("  (the Cloud Run runtime service account needs roles/secretmanager.secretAccessor)");
  }
  console.log("\n  " + cmd.map(shq).join(" ") + "\n");
  if (o.dryRun) console.log("Dry run: nothing deployed.");
  else {
    const r = spawnSync(cmd[0], cmd.slice(1), { stdio: "inherit" });
    if (r.error) throw new UserError("gcloud not found — install the Google Cloud CLI: https://cloud.google.com/sdk/docs/install");
    if (r.status) return r.status;
  }
  console.log("Connect Gemini CLI to it:");
  if (o.pub) console.log(`  npx mcpsmith connect ${o.folder} --url https://<service-url>/mcp`);
  else {
    console.log(`  gcloud run services proxy ${service} --region ${o.region} --port 3000${p}   # keep running`);
    console.log(`  npx mcpsmith connect ${o.folder} --url http://localhost:3000/mcp`);
  }
  return 0;
}

export function connect(o: { folder: string; url?: string; scope: string; name?: string; settings?: string }): number {
  const meta = readMeta(o.folder);
  const serverName = (o.name || meta.slug).replace(/_/g, "-");
  const entry: Record<string, unknown> = o.url
    ? { httpUrl: o.url }
    : {
        command: process.execPath,
        args: [resolve(o.folder, "server.mjs")],
        cwd: resolve(o.folder),
        env: { MCP_TRANSPORT: "stdio", API_BASE_URL: meta.baseUrl, ...Object.fromEntries(meta.secretEnv.map((v) => [v, `$${v}`])) },
      };
  entry.trust = false; // Gemini CLI asks before every tool call
  const path = o.settings ?? join(o.scope === "user" ? homedir() : process.cwd(), ".gemini", "settings.json");
  let data: any = {};
  if (existsSync(path)) {
    try { data = JSON.parse(readFileSync(path, "utf8") || "{}"); } catch (e: any) {
      throw new UserError(`${path} isn't valid JSON (${e.message}); fix it or pass --settings`);
    }
  }
  data.mcpServers ??= {};
  data.mcpServers[serverName] = entry;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify(data, null, 2) + "\n");
  console.log(`Added '${serverName}' to ${path}`);
  if (!o.url) {
    if (!existsSync(join(o.folder, "node_modules"))) console.log(`Install its dependencies once: (cd ${o.folder} && npm install)`);
    if (meta.secretEnv.length) console.log(`Gemini CLI passes these from your shell: export ${meta.secretEnv.map((v) => v + "=…").join(" ")}`);
  }
  console.log("Start Gemini CLI here and run /mcp to see its tools.");
  if (o.url) console.log(`Same thing by hand: gemini mcp add --transport http ${serverName} ${o.url}`);
  return 0;
}
